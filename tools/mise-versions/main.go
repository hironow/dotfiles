var escapes = map[byte]string{'\\': `\\`, '"': `\"`, '\n': `\n`, '\r': `\r`, '\t': `\t`}

func tomlString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		if escaped, ok := escapes[s[i]]; ok {
			b.WriteString(escaped)
			continue
		}
		if s[i] < 0x20 || s[i] == 0x7f {
			fmt.Fprintf(&b, `\u%04X`, s[i])
			continue
		}
		b.WriteByte(s[i])
	}
	b.WriteByte('"')
	return b.String()
}

func tomlKey(key string) string {
	if simpleKey.MatchString(key) {
		return key
	}
	return tomlString(key)
}

func tomlValue(v value) string {
	switch v.kind {
	case kindString:
		return tomlString(v.str)
	case kindTable:
		fields := make([]string, 0, len(v.table.keys))
		for _, key := range v.table.keys {
			fields = append(fields, tomlKey(key)+" = "+tomlValue(v.table.vals[key]))
		}
		return "{ " + strings.Join(fields, ", ") + " }"
	case kindArray:
		items := make([]string, 0, len(v.list))
		for _, item := range v.list {
			items = append(items, tomlString(item))
		}
		return "[" + strings.Join(items, ", ") + "]"
	default:
		return ""
	}
}

// renderValue describes a value in an error message.
func renderValue(v value) string {
	switch v.kind {
	case kindString:
		return strconv.Quote(v.str)
	case kindTable, kindArray:
		return tomlValue(v)
	default:
		return "?"
	}
}

func renderHeredocBody(doc *table) (string, error) {
	settings, ok := doc.child("settings")
	if !ok {
		return "", errors.New("[settings] is missing from the source")
	}
	tools, ok := doc.child("tools")
	if !ok {
		return "", errors.New("[tools] is missing from the source")
	}
	var b strings.Builder
	for _, line := range heredocHeader {
		b.WriteString(line + "\n")
	}
	for _, name := range settings.keys {
		sub, ok := settings.child(name)
		if !ok {
			return "", fmt.Errorf("[settings.%s] is not a table", name)
		}
		b.WriteString("[settings." + tomlKey(name) + "]\n")
		for _, key := range sub.keys {
			b.WriteString(tomlKey(key) + " = " + tomlValue(sub.vals[key]) + "\n")
		}
		b.WriteString("\n")
	}
	b.WriteString("[tools]\n")
	for _, key := range tools.keys {
		b.WriteString(tomlKey(key) + " = " + tomlValue(tools.vals[key]) + "\n")
	}
	body := b.String()
	// Self-check: this must read back as the source's data. A serialization gap
	// stops the run here instead of writing a broken /etc/mise/config.toml.
	got, err := parseTOML(body)
	if err != nil {
		return "", fmt.Errorf("the rendered /etc/mise/config.toml does not parse: %w", err)
	}
	if err := equalDocuments(doc, got, []string{"settings", "tools"}); err != nil {
		return "", fmt.Errorf("the rendered /etc/mise/config.toml differs from the source: %w", err)
	}
	return body, nil
}

func setConstant(text, name, newValue, rel string) (string, error) {
	pattern, err := regexp.Compile(`(?m)^([ \t]*)` + regexp.QuoteMeta(name) + `="[^"]*"`)
	if err != nil {
		return "", err
	}
	if len(pattern.FindAllStringSubmatchIndex(text, -1)) != 1 {
		return "", fmt.Errorf("%s: expected exactly one %s=\"...\" line to generate", rel, name)
	}
	return pattern.ReplaceAllString(text, `${1}`+name+`="`+newValue+`"`), nil
}

func renderFeatureInstall(text string, doc *table) (string, error) {
	loc := heredoc.FindStringSubmatchIndex(text)
	if loc == nil {
		return "", fmt.Errorf("%s: no `cat > /etc/mise/config.toml <<'EOF' ... EOF` block", featureInstallPath)
	}
	body, err := renderHeredocBody(doc)
	if err != nil {
		return "", err
	}
	text = text[:loc[4]] + body + text[loc[5]:]
	for name, keys := range map[string][]string{
		"UV_VERSION":      {"tools", "uv"},
		"JUST_VERSION":    {"tools", "just"},
		"SHELDON_VERSION": {"fetch", "aqua:rossmacarthur/sheldon"},
	} {
		version, err := concrete(doc, keys...)
		if err != nil {
			return "", err
		}
		text, err = setConstant(text, name, version, featureInstallPath)
		if err != nil {
			return "", err
		}
	}
	return text, nil
}

func renderBootstrapInstall(text string, doc *table) (string, error) {
	miseVersion, err := concrete(doc, "bootstrap", "mise")
	if err != nil {
		return "", err
	}
	justVersion, err := concrete(doc, "tools", "just")
	if err != nil {
		return "", err
	}
	if text, err = setConstant(text, "_mise_ver", miseVersion, bootstrapInstallPath); err != nil {
		return "", err
	}
	return setConstant(text, "_just_ver", justVersion, bootstrapInstallPath)
}

// ---------- the document set ----------

type renderedFile struct {
	rel  string
	text string
}

// problemsError carries every inconsistency for a single report.
type problemsError struct{ problems []string }

func (e problemsError) Error() string { return strings.Join(e.problems, "; ") }

func rendered(root string) ([]renderedFile, error) {
	doc, err := loadDoc(filepath.Join(root, sourcePath))
	if err != nil {
		return nil, err
	}
	host, err := loadHostTools(root)
	if err != nil {
		return nil, err
	}
	if problems := validate(doc, host); len(problems) > 0 {
		prefixed := make([]string, 0, len(problems))
		for _, problem := range problems {
			prefixed = append(prefixed, sourcePath+": "+problem)
		}
		return nil, problemsError{problems: prefixed}
	}
	feature, err := readText(filepath.Join(root, featureInstallPath))
	if err != nil {
		return nil, err
	}
	bootstrap, err := readText(filepath.Join(root, bootstrapInstallPath))
	if err != nil {
		return nil, err
	}
	renderedFeature, err := renderFeatureInstall(feature, doc)
	if err != nil {
		return nil, err
	}
	renderedBootstrap, err := renderBootstrapInstall(bootstrap, doc)
	if err != nil {
		return nil, err
	}
	return []renderedFile{
		{featureInstallPath, renderedFeature},
		{bootstrapInstallPath, renderedBootstrap},
	}, nil
}

func readText(path string) (string, error) {
	data, err := os.ReadFile(path) //nolint:gosec // the path comes from this repo's own layout
	if err != nil {
		return "", err
	}
	return string(data), nil
}

func check(root string, stdout, stderr io.Writer) int {
	files, err := rendered(root)
	if err != nil {
		return report(stderr, err)
	}
	stale := 0
	for _, file := range files {
		actual, err := readText(filepath.Join(root, file.rel))
		if err != nil {
			return report(stderr, err)
		}
		if actual == file.text {
			continue
		}
		stale++
		fmt.Fprintf(stdout, "%s: generated region differs from %s\n", file.rel, sourcePath)
		fmt.Fprintf(stdout, "%s\n", firstDifference(actual, file.text))
	}
	if stale == 0 {
		fmt.Fprintln(stdout, "mise-versions: up to date")
		return 0
	}
	fmt.Fprintf(stderr, "\nmise-versions: %d generated file(s) drifted from %s. Run `just mise-versions-sync`.\n", stale, sourcePath)
	return 1
}

// firstDifference shows the first differing line with one line of context.
func firstDifference(actual, want string) string {
	actualLines := strings.Split(actual, "\n")
	wantLines := strings.Split(want, "\n")
	for i := 0; i < len(actualLines) && i < len(wantLines); i++ {
		if actualLines[i] != wantLines[i] {
			return fmt.Sprintf("  line %d:\n    on disk: %s\n    want:    %s", i+1, strconv.Quote(actualLines[i]), strconv.Quote(wantLines[i]))
		}
	}
	return fmt.Sprintf("  the file lengths differ (on disk %d lines, want %d)", len(actualLines), len(wantLines))
}

func sync(root string, stdout, stderr io.Writer) int {
	files, err := rendered(root)
	if err != nil {
		return report(stderr, err)
	}
	written := 0
	for _, file := range files {
		path := filepath.Join(root, file.rel)
		actual, err := readText(path)
		if err != nil {
			return report(stderr, err)
		}
		if actual == file.text {
			continue
		}
		// newline handling: the bytes we render are already LF, and O_WRONLY
		// without translation keeps them LF on every host.
		if err := os.WriteFile(path, []byte(file.text), 0o644); err != nil { //nolint:gosec // tracked repo files
			return report(stderr, err)
		}
		fmt.Fprintf(stdout, "wrote %s\n", file.rel)
		written++
	}
	if written == 0 {
		fmt.Fprintln(stdout, "mise-versions: up to date")
		return 0
	}
	fmt.Fprintf(stdout, "%d file(s) written\n", written)
	return 0
}

func report(stderr io.Writer, err error) int {
	var problems problemsError
	if errors.As(err, &problems) {
		for _, problem := range problems.problems {
			fmt.Fprintf(stderr, "mise-versions: %s\n", problem)
		}
		return 1
	}
	fmt.Fprintf(stderr, "mise-versions: %v\n", err)
	return 1
}

// defaultRoot resolves the checkout from this source file, the same rule the
// Python implementation used (its script's parent). The working directory must
// not matter: `just lint` and `just check` run from the repo root, but a caller
// may be anywhere.
func defaultRoot() (string, error) {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		return "", errors.New("cannot locate this source file to find the checkout")
	}
	return filepath.Clean(filepath.Join(filepath.Dir(file), "..", "..")), nil
}

func run(args []string, stdout, stderr io.Writer) int {
	command := ""
	root := ""
	for i := 0; i < len(args); i++ {
		switch {
		case args[i] == "sync" || args[i] == "check":
			if command != "" {
				return usage(stderr, fmt.Sprintf("unexpected argument %q", args[i]))
			}
			command = args[i]
		case args[i] == "--root":
			if i+1 >= len(args) {
				return usage(stderr, "--root needs a directory")
			}
			root = args[i+1]
			i++
		case strings.HasPrefix(args[i], "--root="):
			root = strings.TrimPrefix(args[i], "--root=")
		default:
			return usage(stderr, fmt.Sprintf("unexpected argument %q", args[i]))
		}
	}
	if command == "" {
		return usage(stderr, "expected `sync` or `check`")
	}
	if root == "" {
		resolved, err := defaultRoot()
		if err != nil {
			return report(stderr, err)
		}
		root = resolved
	}
	if command == "sync" {
		return sync(root, stdout, stderr)
	}
	return check(root, stdout, stderr)
}

func usage(stderr io.Writer, message string) int {
	fmt.Fprintf(stderr, "mise-versions: %s\nusage: mise-versions sync|check [--root DIR]\n", message)
	return 2
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}
