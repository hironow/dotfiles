#!/usr/bin/env python3
"""The image's frozen tool generation, written into the scripts that carry it.

`config/mise/image-tools.toml` is the single source for the versions the
devcontainer bakes into `/etc/mise/config.toml`, fetches as verified tarballs,
and that `install.sh` uses on a bare Linux host before mise exists. This script
is the single writer: `sync` renders those versions into the generated regions,
`check` reports drift. The check is the gate wired into `just lint` (the
pre-commit stage) and `just check` / `just ci`.

Generated regions — everything else in both files is hand-written:

    .devcontainer/features/dotfiles-tools/install.sh
        the body of `cat > /etc/mise/config.toml <<'EOF' ... EOF`
        UV_VERSION / JUST_VERSION   (verified tarballs; versions from [tools])
        SHELDON_VERSION             (tarball-only tool; version from [fetch])
    install.sh
        _mise_ver ([bootstrap].mise) / _just_ver ([tools].just)

The same run keeps the source honest: every `[tools]` and `[fetch]` tool has to
exist in `config/mise/config.toml`, and wherever the host pins an exact version
the two must agree (quint, golangci-lint, cf, sheldon today). `[bootstrap].mise`
is compared with `install.sh`'s `_mise_ver` only — mise is not a mise tool, so
the host config carries no entry for it. Nothing here touches the network.

Why Python and not Go (ROOT_AGENTS.md asks for Go for new tools): this is repo
glue that rewrites two tracked files, not a shipped executable — the closest
existing tool, `scripts/bump_tool.py`, is Python too — and the TOML read/write
comes from the standard library (`tomllib`), where Go would need a new
dependency. The operator ruled on this exception on 2026-10-21 (ADR 0060).
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

SOURCE = Path("config/mise/image-tools.toml")
HOST_CONFIG = Path("config/mise/config.toml")
FEATURE_INSTALL = Path(".devcontainer/features/dotfiles-tools/install.sh")
BOOTSTRAP_INSTALL = Path("install.sh")

# `cat > /etc/mise/config.toml <<'EOF'` ... `EOF` — the body is generated.
_HEREDOC = re.compile(
    r"(?P<open>cat > /etc/mise/config\.toml <<'EOF'\n)(?P<body>.*?)(?P<close>\nEOF\n)",
    re.DOTALL,
)
# A single-line version constant, with its indentation preserved.
_SIMPLE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")
# Host values that are channels rather than pins: nothing to compare against.
_CHANNELS = {"latest", "lts"}
# A version the image may freeze on. mise's request syntax also accepts partial
# versions (`24`), prefixes (`prefix:24`) and the empty string, all of which
# resolve to a moving target — this file must reject them (review #5).
_FULL_VERSION = re.compile(r"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?$")

_HEREDOC_HEADER = (
    "# GENERATED by scripts/mise_versions.py from config/mise/image-tools.toml.",
    "# Do not edit this block: run `just mise-versions-sync`. The rationale for",
    "# these versions (and why the image keeps its own frozen generation) lives in",
    "# that file; `just lint` / `just check` fail when this block drifts.",
)


class Problems(Exception):
    """The source file is inconsistent; nothing is written."""

    def __init__(self, messages: list[str]) -> None:
        super().__init__("; ".join(messages))
        self.messages = messages


def source_path(root: Path) -> Path:
    return root / SOURCE


def load_source(root: Path) -> dict[str, Any]:
    path = source_path(root)
    if not path.is_file():
        raise Problems([f"{SOURCE} is missing: it is the versions' source of truth"])
    return tomllib.loads(path.read_text(encoding="utf-8"))


def host_tools(root: Path) -> dict[str, Any]:
    path = root / HOST_CONFIG
    return tomllib.loads(path.read_text(encoding="utf-8"))["tools"]


def pinned_version(spec: Any) -> str | None:
    """The exact version of a tool entry, or None when it is a channel."""
    if isinstance(spec, dict):
        spec = spec.get("version")
    if not isinstance(spec, str) or spec in _CHANNELS:
        return None
    return spec


# TOML basic strings: escape the quote, the backslash, and the control
# characters. `tomllib` reads these back exactly, so a key or a version that
# needs escaping cannot turn into broken TOML (independent review #4).
_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}


def concrete(source: dict[str, Any], *keys: str) -> str:
    """The exact version at `source[...keys]`, for a generated shell constant.

    A shell constant can only carry a version string: an inline table like
    `uv = { version = "0.13.1" }` must contribute its `version`, not the dict
    (that used to be written out as `UV_VERSION="{'version': ...}"`).
    """
    value: Any = source
    for key in keys:
        value = value[key]
    version = pinned_version(value)
    if version is None or not _FULL_VERSION.match(version):
        raise Problems(
            [
                f"{'.'.join(keys)} must be a full version, not {value!r} (mise would move it)"
            ]
        )
    return version


def _toml_string(value: str) -> str:
    out: list[str] = []
    for char in value:
        if char in _ESCAPES:
            out.append(_ESCAPES[char])
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f"\\u{ord(char):04X}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def _toml_key(key: str) -> str:
    return key if _SIMPLE_KEY.match(key) else _toml_string(key)


def _toml_value(value: Any) -> str:
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, dict):
        inner = ", ".join(
            f"{_toml_key(k)} = {_toml_value(v)}" for k, v in value.items()
        )
        return f"{{ {inner} }}"
    raise Problems([f"unsupported value in the source: {value!r}"])


def fetch_tools(source: dict[str, Any]) -> dict[str, str]:
    """Tarball-fetched tools with their version, whatever channel carries it."""
    fetch = source["fetch"]
    tools = source["tools"]
    out: dict[str, str] = {
        name: tools[name] for name in fetch["mise_tools"] if name in tools
    }
    for key, value in fetch.items():
        if key == "mise_tools":
            continue
        out[key] = value
    return out


def validate(source: dict[str, Any], host: dict[str, Any]) -> None:
    """Refuse an inconsistent source before anything is written."""
    problems: list[str] = []
    for section in ("settings", "tools", "fetch", "bootstrap"):
        if section not in source:
            problems.append(f"{SOURCE}: [{section}] is required")

    tools = source.get("tools", {})
    fetch = source.get("fetch", {})
    bootstrap = source.get("bootstrap", {})

    for name in fetch.get("mise_tools", []):
        if name not in tools:
            problems.append(
                f"{SOURCE}: [fetch].mise_tools names {name!r}, which is not in [tools]"
            )

    # One fact per version: no tool may be versioned in two channels.
    versioned = [
        ("[tools]", set(tools)),
        ("[fetch]", {k for k in fetch if k != "mise_tools"}),
        ("[bootstrap]", set(bootstrap)),
    ]
    seen: dict[str, str] = {}
    for section, keys in versioned:
        for key in sorted(keys):
            if key in seen:
                problems.append(
                    f"{SOURCE}: {key!r} is versioned twice ({seen[key]} and {section}); "
                    "each version belongs in exactly one place"
                )
            seen[key] = section

    # Host parity: the image's tools are the host's tools, and exact pins agree.
    # The source side must be a CONCRETE version: a `latest` there would let the
    # image fetch whatever is newest while the host stays pinned, which is the
    # drift this file exists to prevent (independent review #4).
    for key, value in {**tools, **fetch_tools(source)}.items():
        source_version = pinned_version(value)
        if source_version is None or not _FULL_VERSION.match(source_version):
            problems.append(
                f"{SOURCE}: {key!r} must be a full version, not {value!r}: "
                "a partial/prefix/channel spec resolves to a moving target, and "
                "the image's generation is frozen (ADR 0006)"
            )
        if key not in host:
            problems.append(f"{SOURCE}: {key!r} is not declared in {HOST_CONFIG}")
            continue
        host_version = pinned_version(host[key])
        if host_version is not None and source_version != host_version:
            problems.append(
                f"{SOURCE}: {key!r} is {source_version!r} here but {host_version!r} "
                f"in {HOST_CONFIG}: the image and the host must agree on an exact pin"
            )
    for key, value in bootstrap.items():
        source_version = pinned_version(value)
        if source_version is None or not _FULL_VERSION.match(source_version):
            problems.append(
                f"{SOURCE}: [bootstrap].{key} must be a full version, not {value!r}"
            )

    if problems:
        raise Problems(problems)


def render_heredoc_body(source: dict[str, Any]) -> str:
    lines = list(_HEREDOC_HEADER)
    for section, table in source["settings"].items():
        lines.append(f"[settings.{_toml_key(section)}]")
        for key, value in table.items():
            lines.append(f"{_toml_key(key)} = {_toml_value(value)}")
        lines.append("")
    lines.append("[tools]")
    for key, value in source["tools"].items():
        lines.append(f"{_toml_key(key)} = {_toml_value(value)}")
    body = "\n".join(lines) + "\n"
    # Self-check: this must read back as the source's data. A serialization gap
    # (an unescaped quote, a dropped sub-table) stops the run here instead of
    # writing a broken /etc/mise/config.toml into the image (review #4).
    reparsed = tomllib.loads(body)
    expected = {"settings": source["settings"], "tools": source["tools"]}
    if reparsed != expected:
        raise Problems(
            ["the generated /etc/mise/config.toml does not round-trip through tomllib"]
        )
    return body


def _set_constant(text: str, name: str, value: str, path: Path) -> str:
    pattern = re.compile(rf'^(?P<indent>[ \t]*){re.escape(name)}="[^"]*"', re.MULTILINE)
    if len(pattern.findall(text)) != 1:
        raise Problems([f'{path}: expected exactly one {name}="..." line to generate'])
    return pattern.sub(rf'\g<indent>{name}="{value}"', text)


def render_feature_install(text: str, source: dict[str, Any]) -> str:
    match = _HEREDOC.search(text)
    if not match:
        raise Problems(
            [
                f"{FEATURE_INSTALL}: no `cat > /etc/mise/config.toml <<'EOF' ... EOF` block"
            ]
        )
    text = (
        text[: match.start("body")]
        + render_heredoc_body(source)
        + text[match.end("body") :]
    )
    text = _set_constant(
        text, "UV_VERSION", concrete(source, "tools", "uv"), FEATURE_INSTALL
    )
    text = _set_constant(
        text, "JUST_VERSION", concrete(source, "tools", "just"), FEATURE_INSTALL
    )
    sheldon = concrete(source, "fetch", "aqua:rossmacarthur/sheldon")
    return _set_constant(text, "SHELDON_VERSION", sheldon, FEATURE_INSTALL)


def render_bootstrap_install(text: str, source: dict[str, Any]) -> str:
    text = _set_constant(
        text, "_mise_ver", concrete(source, "bootstrap", "mise"), BOOTSTRAP_INSTALL
    )
    return _set_constant(
        text, "_just_ver", concrete(source, "tools", "just"), BOOTSTRAP_INSTALL
    )


def rendered(root: Path) -> dict[Path, str]:
    """The two scripts as this source would write them."""
    source = load_source(root)
    validate(source, host_tools(root))
    feature = (root / FEATURE_INSTALL).read_text(encoding="utf-8")
    bootstrap = (root / BOOTSTRAP_INSTALL).read_text(encoding="utf-8")
    return {
        FEATURE_INSTALL: render_feature_install(feature, source),
        BOOTSTRAP_INSTALL: render_bootstrap_install(bootstrap, source),
    }


def drift(root: Path) -> list[str]:
    """Paths whose generated regions do not match the source."""
    stale: list[str] = []
    for path, expected in rendered(root).items():
        if (root / path).read_text(encoding="utf-8") != expected:
            stale.append(str(path))
    return stale


def diff_for(path: Path, actual: str, expected: str) -> str:
    return "".join(
        difflib.unified_diff(
            actual.splitlines(keepends=True),
            expected.splitlines(keepends=True),
            fromfile=f"a/{path}",
            tofile=f"b/{path}",
        )
    )


def sync(root: Path) -> list[Path]:
    written: list[Path] = []
    for path, expected in rendered(root).items():
        target = root / path
        if target.read_text(encoding="utf-8") != expected:
            # newline="\n": never let the host OS rewrite these to CRLF (ADR 0020).
            target.write_text(expected, encoding="utf-8", newline="\n")
            written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("sync", "check"))
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="checkout to operate on",
    )
    args = parser.parse_args(argv)

    root: Path = args.root
    try:
        if args.command == "sync":
            written = sync(root)
            for path in written:
                print(f"wrote {path}")
            print("up to date" if not written else f"{len(written)} file(s) written")
            return 0
        rendered_files = rendered(root)
        stale = [
            path
            for path in rendered_files
            if (root / path).read_text(encoding="utf-8") != rendered_files[path]
        ]
        if not stale:
            print("mise-versions: up to date")
            return 0
        for path in stale:
            print(
                diff_for(
                    path,
                    (root / path).read_text(encoding="utf-8"),
                    rendered_files[path],
                ),
                end="",
            )
        print(
            f"\nmise-versions: {len(stale)} generated file(s) drifted from {SOURCE}. "
            "Run `just mise-versions-sync`.",
            file=sys.stderr,
        )
        return 1
    except Problems as problems:
        for message in problems.messages:
            print(f"mise-versions: {message}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
